// kernel-typed.mjs: Candela's fixed kernel and the gallery's scene sections in Typed (PICOCALC-CANDELA-TYPED), next to
// kernel.mjs (the same WGSL to C++). regenerate.mjs calls generateTypedGallery() and writes its files into
// apps/typed/candela-gallery/; the lowering is typed/ (parse.mjs, lower.mjs, program.mjs, values.mjs).
//
// Returns { files: { 'types.typed', 'kernel.typed', 'scenes.typed', 'glue.typed', 'layout.json' }, stats }. The app's
// source is types.typed + compiler/typed/lib/math.typed + kernel.typed + scenes.typed + glue.typed (app.json).
import { readFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkPin, loadKernel, loadCandela, loadPresets, exportScene, splitProgram, fixedParts, PIN } from './lib/candela.mjs';
import { generateTypedProgram } from './typed/program.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
export const MATH_TYPED = resolve(HERE, '../../../compiler/typed/lib/math.typed');

export function mathNames() {
  return new Set([...readFileSync(MATH_TYPED, 'utf8').matchAll(/^function\s+(\w+)/gm)].map(m => m[1]));
}

// The scenes' sections as the gallery prepares them (scenes.mjs runs the same front end).
export async function gallerySections(root, gallery, only) {
  const K = await loadKernel(root), C = await loadCandela(root);
  const presets = loadPresets(root);
  const out = [];
  for (const [id, size] of gallery.scenes) {
    if (only && !only.includes(id)) continue;
    const preset = presets.find(p => p.id === id);
    if (!preset) throw new Error('no preset ' + id);
    const { compiled, bin } = await exportScene(root, C, preset, size, size);
    const s = splitProgram(compiled.shared, K);
    out.push({ id, size, spectral: s.spectral, fieldCode: s.fieldCode, matCode: s.matCode, bin });
  }
  return out;
}

export async function generateTypedGallery(root, gallery, { only } = {}) {
  const unpinned = checkPin(root);
  const K = await loadKernel(root);
  const kernelWGSL = fixedParts(K).map(([name, text]) => `// ---- ${name} ----\n${text}`).join('\n');
  const scenes = await gallerySections(root, gallery, only);
  const p = generateTypedProgram(kernelWGSL, scenes, mathNames());
  const head = (what) => `// ${what}: generated by tools/gen/candela/kernel-typed.mjs from Candela ${unpinned.length ? 'UNPINNED' : 'archive ' + PIN.archive.slice(0, 16)}
// (src/kernel.js ${PIN['src/kernel.js'].slice(0, 16)}); do not edit: change the generator and run tools/gen/candela/regenerate.mjs.\n`;
  const sceneList = scenes.map((s, i) => `// scene ${i}: ${s.id} (${s.size} x ${s.size}${s.spectral ? ', spectral' : ''})`).join('\n');
  const files = {
    'types.typed': head('records: Candela\'s structs, the functions\' static frames, the kernel record K') + p.types + '\n',
    'kernel.typed': head('Candela\'s fixed kernel with the C++ kernel\'s CPU substitutions') + p.kernel + '\n',
    'scenes.typed': head('the gallery\'s scene sections and the five dispatchers\' targets') + sceneList + '\n' + p.scenes + '\n',
    'glue.typed': head('the entry points: cdlLayout, cdlInit, cdlSky, cdlRenderSpan') + p.glue + '\n',
    'layout.json': JSON.stringify({ note: 'generated by tools/gen/candela/kernel-typed.mjs; the scene order of K.scene', scenes: scenes.map(s => s.id),
      arenaWords: p.layout.arenaWords, kFields: p.layout.kFields }, null, 1) + '\n',
  };
  return { files, stats: p.stats, scenes };
}

// The program's source in the app's order (what app.json assembles).
export function assemble(files) {
  return [files['types.typed'], readFileSync(MATH_TYPED, 'utf8'), files['kernel.typed'], files['scenes.typed'], files['glue.typed']].join('\n');
}

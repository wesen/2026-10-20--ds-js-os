// kernel.mjs: the firmware C++ of Candela's fixed path-tracing kernel and post pass, generated from Candela's WGSL.
// Promoted from PICOCALC-CANDELA-CPU-KERNEL scripts/02-gen-kernel.mjs; regenerate.mjs calls generateKernel().
//
// Reads src/kernel.js (PRELUDE, SPECTRAL, CORE, PATH, POST, ggxTableWGSL) and src/render.js (displaySource:
// POST plus denoisePx and displayPx) from the vendored Candela and returns
//   cdl_kernel.h    vector prologue, constants, structs, the Sections dispatch table, the section API
//   cdl_kernel.cpp  the fixed kernel (internal functions static), CPU override points, C entry points
//   cdl_post.cpp    the display and denoise passes
//   manifest.json   what was generated from which WGSL
// and the exact WGSL translated (kernel.wgsl, post.wgsl; not vendored). The section API (the kernel functions that
// generated sections may call) is translator/isa.js SECTION_API, the same list the section translator compiles
// against. The hand-written parts the generated code includes (cdl_switches.h, cdl_api.h, cdl_math.h,
// cdl_overrides.inc, cdl_post.inc) are the primary copies in picocalc-os/third_party/candela/kernel/.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { checkPin, loadKernel, fixedParts, PIN, sha256 } from './lib/candela.mjs';
import { translate, rewriteFn, prologue, head, args, body } from './lib/wgsl2c.mjs';
import { SECTION_API } from './translator/isa.js';

export const ACCESSORS = ['U', 'objF', 'litF', 'bvhF', 'sdF'];
// The five functions the fixed kernel calls in generated code (compile.js builds them per scene).
export const DISPATCH = [
  { name: 'evalMaterial', ret: 'Lobe', params: [['h', 'Hit'], ['wo', 'vec3f'], ['u', 'f32']] },
  { name: 'sdUser', ret: 'f32', params: [['k', 'i32'], ['p', 'vec3f']] },
  { name: 'heightAt', ret: 'f32', params: [['k', 'i32'], ['xz', 'vec2f']] },
  { name: 'densityOf', ret: 'f32', params: [['m', 'i32'], ['P', 'vec3f']] },
  { name: 'customKernel', ret: 'vec3f', params: [['ro', 'vec3f'], ['rd', 'vec3f']] },
].map(d => ({ ...d, params: d.params.map(([name, type]) => ({ name, type, cpp: ['Hit', 'Lobe'].includes(type) ? `const ${type}& ${name}` : `${type} ${name}` })) }));
// CPU substitutions that replace a kernel function: a hand-written implementation in cdl_overrides.inc,
// or a rewrite of Candela's own body (the pattern must occur exactly once).
const OVERRIDES = [
  { fn: 'hash3', sw: 'CDL_INT_HASH', impl: 'cdl_cpu_hash3' },
  { fn: 'hash13', sw: 'CDL_INT_HASH', impl: 'cdl_cpu_hash13' },
  { fn: 'voronoi3', sw: 'CDL_INT_HASH', rewrite: ['fract(sin(cell.x * 7.1 + cell.y * 157.3 + cell.z * 113.7) * 43758.5453)', 'hash13(cell)'] },
  { fn: 'skyL', sw: 'CDL_SKY_TABLE', impl: 'cdl_cpu_skyL' },
];
const POST_OVERRIDES = [{ fn: 'atrousW', sw: 'CDL_POW32', rewrite: ['pow(dn, sn)', 'powSn(dn, sn)'] }];
const POST_KNOWN = ['D', 'W', 'cAt', 'aAt', 'nAt', 'sq', 'lum', 'safeNorm', 'powSn'];

// The provenance comment at the top of every generated C++ file.
function provenance(root, unpinned) {
  return `// Generated by tools/gen/candela/kernel.mjs from Candela ${unpinned.length ? 'UNPINNED' : 'archive ' + PIN.archive.slice(0, 16)}
// src/kernel.js ${sha256(readFileSync(join(root, 'src/kernel.js')))}, src/render.js ${sha256(readFileSync(join(root, 'src/render.js')))}
// Do not edit: change the generator or the hand-written cdl_*.h and *.inc here, and run tools/gen/candela/regenerate.mjs.`;
}
const overrideHow = (o) => o.impl ? 'cdl_overrides.inc ' + o.impl : `rewrite '${o.rewrite[0]}' -> '${o.rewrite[1]}'`;

export async function generateKernel(root) {
  const unpinned = checkPin(root);
  const K = await loadKernel(root);
  const R = await import(pathToFileURL(join(root, 'src/render.js')).href);
  const API = SECTION_API;
  const pinNote = provenance(root, unpinned);

  // ---- translate the fixed kernel ----
  const kernelWGSL = fixedParts(K).map(([name, text]) => `// ---- ${name} ----\n${text}`).join('\n');
  const kt = translate(kernelWGSL, { where: 'fixed kernel', known: [...ACCESSORS, ...DISPATCH.map(d => d.name)] });
  for (const n of [...API, ...OVERRIDES.map(o => o.fn)]) if (!kt.defined.has(n)) throw new Error(`kernel.mjs: ${n} is not a fixed-kernel function`);
  for (const d of DISPATCH) if (kt.defined.has(d.name)) throw new Error(`kernel.mjs: ${d.name} is defined in the fixed kernel; it should be generated`);
  if (kt.tables.length !== 1 || kt.tables[0].name !== 'ETAB') throw new Error('kernel.mjs: expected exactly the GGX table ETAB as initialised private data');
  if (/\bETAB\s*\[[^\]]*\]\s*=[^=]/.test(kernelWGSL)) throw new Error('kernel.mjs: ETAB is written; it cannot be const');

  const P = prologue();
  const structDefs = (t) => t.structs.map(s => `struct ${s.name} {\n${s.members.join('\n')}\n};`).join('\n');
  const sectionsStruct = `// The scene's generated code, reached through this table (a scene's NS_sections_<ID>, or the section
// interpreter's bytecode entry points, ../vm).
struct Sections {
${DISPATCH.map(d => `  ${d.ret} (*${d.name})(${d.params.map(p => p.cpp).join(', ')});`).join('\n')}
};`;
  const apiFns = API.map(n => kt.fns.find(f => f.name === n));
  const header = `${pinNote}
#pragma once
#include <stdint.h>
#include <string.h>
#include "cdl_switches.h"
#include "cdl_api.h"
namespace CDL_NS {
typedef float f32; typedef int i32; typedef unsigned u32;
${P.types}
#include "cdl_math.h"
${P.ops}
static const bool SPECTRAL_ON = CDL_SPECTRAL != 0;
${kt.consts.map(c => `static const ${c.type} ${c.name} = ${c.init};`).join('\n')}
${structDefs(kt)}
${sectionsStruct}
extern const Sections *gSec;
${kt.globals.map(g => `extern ${g.type} ${g.name};`).join('\n')}
// the packed buffers, bound by NS_bind (render.js binds the same rows to GPU storage buffers)
extern const vec4f *cdlU, *cdlO, *cdlL, *cdlB, *cdlS;
inline vec4f U(i32 i) { return cdlU[i]; }    inline vec4f objF(i32 i) { return cdlO[i]; }
inline vec4f litF(i32 i) { return cdlL[i]; } inline vec4f bvhF(i32 i) { return cdlB[i]; }
inline vec4f sdF(i32 i) { return cdlS[i]; }
// The section API: the kernel functions that generated sections call (translator/isa.js SECTION_API, 105 presets).
namespace api {
${apiFns.map(f => `${head(f, f.name, '')};`).join('\n')}
}
} // namespace CDL_NS
extern "C" { CDL_DECLARE_INSTANCE(CDL_NS) }
`;

  // definitions with override points
  const ovr = new Map(OVERRIDES.map(o => [o.fn, o]));
  function emitFns(t, overrides, ctx) {
    const protos = [], defs = [];
    for (const f of t.fns) {
      const o = overrides.get(f.name);
      if (!o) { protos.push(head(f) + ';'); defs.push(head(f) + body(f)); continue; }
      protos.push(head(f, f.name + '_wgsl') + ';', head(f) + ';');
      defs.push(head(f, f.name + '_wgsl') + body(f));
      let alt = o.impl;
      if (o.rewrite) {
        const g = rewriteFn(f, o.rewrite[0], o.rewrite[1], ctx);
        protos.push(`#if ${o.sw}\n${head(g, f.name + '_cpu')};\n#endif`);
        defs.push(`#if ${o.sw}\n${head(g, f.name + '_cpu')}${body(g)}\n#endif`);
        alt = f.name + '_cpu';
      }
      defs.push(`${head(f)} {\n#if ${o.sw}\n  return ${alt}(${args(f)});\n#else\n  return ${f.name}_wgsl(${args(f)});\n#endif\n}`);
    }
    return { protos, defs };
  }
  const kctx = { where: 'fixed kernel (rewrite)', known: [...kt.defined, ...ACCESSORS, ...DISPATCH.map(d => d.name), 'hash13'], structs: [...kt.structNames],
    impure: { fns: kt.impure, globals: kt.globals.map(g => g.name) } };
  const ke = emitFns(kt, ovr, kctx);
  const tab = kt.tables[0];
  const kernel = `${pinNote}
#include "cdl_kernel.h"
namespace CDL_NS {
const Sections *gSec = nullptr;
const vec4f *cdlU, *cdlO, *cdlL, *cdlB, *cdlS;
${kt.globals.map(g => `${g.type} ${g.name} = ${g.init};`).join('\n')}
// the GGX directional-albedo table: ggxTableWGSL() evaluated once, at generation time
static const ${tab.type} ${tab.name}[${tab.n}] = {${tab.init}};
${ke.protos.join('\n')}
${DISPATCH.map(d => `static ${d.ret} ${d.name}(${d.params.map(p => p.cpp).join(', ')});`).join('\n')}
#include "cdl_overrides.inc"
#if CDL_MONO
// one translation unit with the scene's sections (the prototype's arrangement, for comparison)
#include CDL_MONO_SCENE
#endif
${ke.defs.join('\n')}
// ---- the dispatch seam ----
${DISPATCH.map(d => `static ${d.ret} ${d.name}(${d.params.map(p => p.cpp).join(', ')}) {
#if CDL_MONO
  return sec_${d.name}(${d.params.map(p => p.name).join(', ')});
#else
  return gSec->${d.name}(${d.params.map(p => p.name).join(', ')});
#endif
}`).join('\n')}
// ---- the section API, with external linkage ----
namespace api {
${apiFns.map(f => `${head(f, f.name, '')} { return CDL_NS::${f.name}(${args(f)}); }`).join('\n')}
}
static_assert(sizeof(PixOut) == sizeof(cdl_pixout), "PixOut layout");
} // namespace CDL_NS

extern "C" int CDL_C(bind)(const cdl_buffers *b, const void *sections, void *sky) {
  using namespace CDL_NS;
  cdlU = (const vec4f *)b->U; cdlO = (const vec4f *)b->O; cdlL = (const vec4f *)b->LI; cdlB = (const vec4f *)b->BV; cdlS = (const vec4f *)b->SD;
  gSec = (const Sections *)sections;
  if (!CDL_MONO && !sections) return 0;
  int r = 1;
#if CDL_SKY_TABLE
  if (cdl_sky_bind(sky)) r = 2;
#else
  (void)sky;
#endif
  return r;
}
extern "C" unsigned CDL_C(sky_bytes)(void) {
#if CDL_SKY_TABLE
  return sizeof(CDL_NS::SkyWs);
#else
  return 0;
#endif
}
static inline void cdl_store(cdl_pixout *out, const CDL_NS::PixOut &o) {   // field by field: GCC calls memcpy for 48 bytes
  const CDL_NS::vec4f *v[3] = {&o.c, &o.alb, &o.nrm};
  float *dst[3] = {out->c, out->alb, out->nrm};
  for (int k = 0; k < 3; k++) { dst[k][0] = v[k]->x; dst[k][1] = v[k]->y; dst[k][2] = v[k]->z; dst[k][3] = v[k]->w; }
}
// a run of pixels of one row: renderPixel (one caller) is inlined into this loop, so a sample pays no call overhead
extern "C" void CDL_C(render_span)(int y, int x0, int x1, unsigned frame, cdl_pixout *out) {
  for (int x = x0; x < x1; x++) cdl_store(out++, CDL_NS::renderPixel(CDL_NS::vec2f(CDL_NS::f32(x), CDL_NS::f32(y)), frame));
}
extern "C" void CDL_C(render_pixel)(int x, int y, unsigned frame, cdl_pixout *out) { CDL_C(render_span)(y, x, x + 1, frame, out); }
`;

  // ---- the post pass: POST + denoisePx + displayPx, as render.js assembles it without user passes ----
  const postWGSL = R.displaySource([]);
  if (!postWGSL.startsWith(K.POST)) throw new Error('kernel.mjs: displaySource() no longer starts with POST');
  const pt = translate(postWGSL, { where: 'post', known: POST_KNOWN });
  for (const n of ['displayPx', 'denoisePx', 'atrousW', 'tonemap']) if (!pt.defined.has(n)) throw new Error('kernel.mjs: post lacks ' + n);
  if (pt.structs.length || pt.globals.length || pt.tables.length) throw new Error('kernel.mjs: post declares module-scope state');
  const pe = emitFns(pt, new Map(POST_OVERRIDES.map(o => [o.fn, o])), { where: 'post (rewrite)', known: [...pt.defined, ...POST_KNOWN] });
  const post = `${pinNote}
#include "cdl_kernel.h"
namespace CDL_NS {
#include "cdl_post.inc"
${pt.consts.map(c => `static const ${c.type} ${c.name} = ${c.init};`).join('\n')}
${pe.protos.join('\n')}
${pe.defs.join('\n')}
} // namespace CDL_NS
extern "C" void CDL_C(post_bind)(const float *src, const float *alb, const float *nrm, const float *Drows) {
  using namespace CDL_NS;
  gPostSrc = (const vec4f *)src; gPostAlb = (const vec4f *)alb; gPostNrm = (const vec4f *)nrm; gPostD = (const vec4f *)Drows;
}
extern "C" void CDL_C(display_px)(int x, int y, float *o) {
  using namespace CDL_NS;
  const vec4f c = displayPx(vec2i(x, y), vec2i(W(), i32(D(0).y)));
  o[0] = c.x; o[1] = c.y; o[2] = c.z; o[3] = c.w;
}
extern "C" void CDL_C(denoise_px)(int x, int y, float *o) {
  using namespace CDL_NS;
  const vec3f c = denoisePx(vec2i(x, y), i32(D(4).x), vec2i(W(), i32(D(0).y)), D(4).y, D(0).w);
  o[0] = c.x; o[1] = c.y; o[2] = c.z;
}
`;

  const manifest = { pin: PIN, unpinned, kernel: { wgslLines: kernelWGSL.split('\n').length, functions: kt.fns.length, structs: kt.structs.map(s => s.name), globals: kt.globals.map(g => g.name), consts: kt.consts.map(c => c.name),
      sideEffects: kt.impure, sequenced: kt.sequenced },
    sectionAPI: API, dispatch: DISPATCH.map(d => d.name), overrides: OVERRIDES.map(o => ({ fn: o.fn, switch: o.sw, how: overrideHow(o) })),
    post: { wgslLines: postWGSL.split('\n').length, functions: pt.fns.length, overrides: POST_OVERRIDES.map(o => ({ fn: o.fn, switch: o.sw, how: `rewrite '${o.rewrite[0]}' -> '${o.rewrite[1]}'` })) } };
  return {
    files: { 'cdl_kernel.h': header, 'cdl_kernel.cpp': kernel, 'cdl_post.cpp': post, 'manifest.json': JSON.stringify(manifest, null, 1) + '\n' },
    wgsl: { kernel: kernelWGSL, post: postWGSL },
    summary: `kernel: ${kt.fns.length} functions, ${kt.structs.length} structs, ${API.length} exported; post: ${pt.fns.length} functions`,
  };
}

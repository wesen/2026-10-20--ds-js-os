#!/usr/bin/env python3
"""Make nucleus/font_paper.h: anti-aliased proportional fonts for the PaperS3's 16-gray panel.

Each glyph is rasterized with PIL from a TTF into a cell of the font's line height, stored as one 4-bit
alpha value per pixel (two per byte, the format gfx.c blends), with its advance in pixels. A cell starts
`pad` pixels left of the pen so glyphs that overhang to the left (j, f, italics) keep their ink. Symbols a
face lacks (arrows, box drawing, the return key) are taken from DejaVu Sans at the same size.

Faces (all free licences, see third_party/fonts/): Charis SIL (OFL) for text, Liberation Sans Bold (OFL)
for titles and numerals, DejaVu Sans Mono (Bitstream Vera licence) for tables and the REPL.

    python3 tools/gen_paper_font.py [out.h]
"""
import sys
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

TT = "/usr/share/fonts/truetype"
CHARIS, CHARIS_B = f"{TT}/charis/CharisSIL-Regular.ttf", f"{TT}/charis/CharisSIL-Bold.ttf"
LIB_B = f"{TT}/liberation/LiberationSans-Bold.ttf"
MONO = f"{TT}/dejavu/DejaVuSansMono.ttf"
FALLBACK = f"{TT}/dejavu/DejaVuSans.ttf"

EXTRA = "▸▾◂•…←→↑↓▲▼✓✕°·█▒░─│┌┐└┘├┤┬┴┼⏎⌫äöüÄÖÜßéèàçñ–—‘’“”×÷±≤≥µ⇧"
CHARS = [chr(c) for c in range(32, 127)] + list(dict.fromkeys(EXTRA))

# name, face, pixel size
FONTS = [("s", CHARIS, 20), ("m", CHARIS, 26), ("mb", CHARIS_B, 26), ("l", LIB_B, 36), ("xl", LIB_B, 64),
         ("mono", MONO, 20), ("monos", MONO, 16)]


def covers(path):
    cmap = TTFont(path)["cmap"].getBestCmap()
    return lambda ch: ord(ch) in cmap


def build(name, path, size):
    font, fb = ImageFont.truetype(path, size), ImageFont.truetype(FALLBACK, size)
    has = covers(path)
    faces = [font if has(ch) or ch == " " else fb for ch in CHARS]
    boxes = [f.getbbox(ch, anchor="ls") for f, ch in zip(faces, CHARS)]
    # the cell is as tall as the ink of the whole set (the faces' own ascent and descent leave a lot of air);
    # the compositor adds line spacing
    asc = -min(b[1] for b in boxes)
    h = asc + max(b[3] for b in boxes) + 1
    pad = max(0, -min(b[0] for b in boxes))
    w = max(pad + b[2] for b in boxes) + 1
    adv = [max(1, round(f.getlength(ch))) for f, ch in zip(faces, CHARS)]
    data = []
    for f, ch in zip(faces, CHARS):
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((pad, asc), ch, font=f, fill=255, anchor="ls")
        px = list(img.tobytes())
        nib = [min(15, (v + 8) // 17) for v in px]
        if len(nib) % 2: nib.append(0)
        data.extend((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
    return dict(name=name, w=w, h=h, pad=pad, adv=adv, data=data)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "nucleus/font_paper.h"
    fonts = [build(*f) for f in FONTS]
    L = ["// Generated by tools/gen_paper_font.py. Do not edit.",
         "// Charis SIL and Liberation Sans (SIL Open Font License 1.1), DejaVu Sans Mono and DejaVu Sans (Bitstream",
         "// Vera licence): rasterized subsets, see third_party/fonts/.",
         "#pragma once", "#include <stdint.h>",
         f"#define FONT_GLYPHS {len(CHARS)}",
         "static const uint32_t font_codepoints[FONT_GLYPHS] = {" + ",".join(str(ord(c)) for c in CHARS) + "};"]
    for f in fonts:
        L.append(f"static const uint8_t font_{f['name']}_adv[FONT_GLYPHS] = {{" + ",".join(map(str, f["adv"])) + "};")
        L.append(f"static const uint8_t font_{f['name']}_data[] = {{")
        d = f["data"]
        for i in range(0, len(d), 32):
            L.append("  " + ",".join(map(str, d[i:i + 32])) + ",")
        L.append("};")
    L.append("typedef struct { const char *name; int w, h; const uint8_t *data; const uint8_t *adv; int pad; } font_def_t;   // adv NULL: monospace")
    L.append("static const font_def_t font_table[] = {")
    for f in fonts:
        L.append(f"  {{ \"{f['name']}\", {f['w']}, {f['h']}, font_{f['name']}_data, font_{f['name']}_adv, {f['pad']} }},")
    L.append("};")
    L.append(f"#define FONT_COUNT {len(fonts)}")
    open(out, "w").write("\n".join(L) + "\n")
    for f in fonts:
        print(f"{f['name']:5s} cell {f['w']}x{f['h']} pad {f['pad']}  '0' advance {f['adv'][16]}  {len(f['data']) // 1024} KB")


main()

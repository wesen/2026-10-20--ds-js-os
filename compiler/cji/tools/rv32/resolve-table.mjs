#!/usr/bin/env node
// CJI-4 (chapter 30): the names a world's module may link to, as a table for the firmware.
//
//   node tools/rv32/resolve-table.mjs --board native_elf_p4.c [--lib OBJ...] --cji OBJ... [--map NAME=SYMBOL...]
//       [--name TABLE] > table.c
//
// picocalc-os's native backend gives a module only what its resolve() lists (port/esp32p4/optional/
// native_elf/native_elf_p4.c: SYMS, a C library subset and libgcc's helpers). A compiled world also
// needs the runtime, the glue (runtime/cji_elf.c) and, with units, the world runtime's unit: every
// global symbol of the --cji objects (ELF32 relocatable objects for RISC-V, read here). The output is
// a C file with one table, { name, address }, NULL-free, and its length:
//
//   - for the board (--name cji_resolve): the --cji symbols only, the table resolve() would search
//     after its own SYMS;
//   - for the rv32 test firmware (the default, fw_resolve, which bench/emu/emu.c's loader searches):
//     the board's own names as well, each as the --lib objects define it (a name the test firmware
//     does not define is not offered), or as --map NAME=SYMBOL says (the fake kernel's charging
//     allocator for malloc, as native_elf_p4.c maps malloc to m_malloc).
//
// Symbols are referred to by asm labels, so names that are not C identifiers (cji_f_JSON$value.ef56...)
// are fine.
import { readFileSync } from 'node:fs';

const args = process.argv.slice(2);
const groups = { '--board': [], '--lib': [], '--cji': [], '--map': [], '--name': [] };
let cur = null;
for (const a of args) {
  if (a in groups) cur = a;
  else if (cur) groups[cur].push(a);
  else { console.error(`resolve-table: ${a}: which group?`); process.exit(2); }
}
const table = groups['--name'][0] ?? 'fw_resolve';
const forBoard = table !== 'fw_resolve';

// an ELF32 object's defined global symbols
function globals(path) {
  const b = readFileSync(path);
  if (b.readUInt32BE(0) !== 0x7f454c46 || b[4] !== 1) throw new Error(`${path}: not an ELF32 object`);
  const shoff = b.readUInt32LE(32), shentsize = b.readUInt16LE(46), shnum = b.readUInt16LE(48);
  const sec = (i) => ({ type: b.readUInt32LE(shoff + i * shentsize + 4), offset: b.readUInt32LE(shoff + i * shentsize + 16),
    size: b.readUInt32LE(shoff + i * shentsize + 20), link: b.readUInt32LE(shoff + i * shentsize + 24) });
  const out = [];
  for (let i = 0; i < shnum; i++) {
    const s = sec(i);
    if (s.type !== 2) continue;   // SHT_SYMTAB
    const str = sec(s.link);
    for (let o = s.offset; o < s.offset + s.size; o += 16) {
      const name = b.readUInt32LE(o), info = b[o + 12], shndx = b.readUInt16LE(o + 14), bind = info >> 4;
      if ((bind === 1 || bind === 2) && shndx !== 0) {   // GLOBAL or WEAK, defined
        let e = str.offset + name;
        while (b[e]) e++;
        out.push(b.toString('latin1', str.offset + name, e));
      }
    }
  }
  return out;
}

// the board's own list: SYMS[] and HELPERS(X) in native_elf_p4.c
function boardNames(path) {
  const src = readFileSync(path, 'utf8');
  const names = [];
  const syms = src.slice(src.indexOf('SYMS[] = {'), src.indexOf('};', src.indexOf('SYMS[] = {')));
  for (const m of syms.matchAll(/\{\s*"([^"]+)"/g)) names.push(m[1]);
  const helpers = src.slice(src.indexOf('#define HELPERS(X)'), src.indexOf('#define DECLARE'));
  for (const m of helpers.matchAll(/X\((\w+)\)/g)) names.push(m[1]);
  return names;
}

const entries = new Map();   // name -> symbol
const map = new Map(groups['--map'].map((m) => m.split('=')));
if (!forBoard) {
  const defined = new Set(groups['--lib'].flatMap(globals));
  for (const name of groups['--board'].flatMap(boardNames)) {
    const sym = map.get(name) ?? name;
    if (map.has(name) || defined.has(name)) entries.set(name, sym);
  }
}
for (const name of groups['--cji'].flatMap(globals)) if (!entries.has(name)) entries.set(name, name);

const lines = [`/* generated by tools/rv32/resolve-table.mjs: the names a compiled world's module may link to (${entries.size}) */`];
let k = 0;
for (const sym of new Set(entries.values())) lines.push(`extern char cji_r${k++}[] __asm__("${sym}");`);
const index = new Map([...new Set(entries.values())].map((s, i) => [s, i]));
lines.push(`const struct { const char *name; void *addr; } ${table}[] = {`);
for (const [name, sym] of entries) lines.push(`\t{ "${name}", cji_r${index.get(sym)} },`);
lines.push('};', `const int ${table.replace(/resolve$/, 'nresolve')} = ${entries.size};`, '');
process.stdout.write(lines.join('\n'));

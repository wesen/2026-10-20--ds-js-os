#!/usr/bin/env node
// CJI-3: writes src/prelude-exports.js, the world runtime's export list (world-native.js
// preludeExports: the runtime's names a world may use, in source order) and the record key orders
// its parse notes, so that a world compiled on its own (nativeWorldUnit) need not parse the whole
// runtime to learn them. Run it whenever
// NATIVE_WORLD_SOURCE changes: compiling the runtime's unit (nativePreludeUnit) and the test suite
// both check the list against the runtime and fail while it is stale.
import { writeFileSync } from 'node:fs';
import { preludeFacts } from '../src/world-native.js';

const { exports: list, keyOrders } = preludeFacts();
const text = `// Generated by tools/gen-prelude-exports.mjs from src/world-native.js (NATIVE_WORLD_SOURCE): do not
// edit. The world runtime's names a world may use, in source order (the export record's slots);
// mutable: a let, which a world reads through a function. Checked against the runtime by
// nativePreludeUnit and by the test suite.
export const PRELUDE_EXPORTS = [
${list.map((e) => `  { name: '${e.name}', mutable: ${e.mutable} },`).join('\n')}
];
// The record key orders parsing the runtime notes (types.js noteKeyOrder), in order: a world compiled
// on its own notes them after its own, as when the runtime was parsed after it, so that its records
// are laid out alike.
export const PRELUDE_KEY_ORDERS = [
${keyOrders.map((ns) => `  [${ns.map((n) => `'${n}'`).join(', ')}],`).join('\n')}
];
`;
writeFileSync(new URL('../src/prelude-exports.js', import.meta.url), text);
console.log(`wrote src/prelude-exports.js: ${list.length} names, ${keyOrders.length} key orders`);

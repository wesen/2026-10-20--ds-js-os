#!/usr/bin/env python3
"""Replace the three bundlers' build.mjs with the versions that call compiler/typed/bundle.mjs.

usage: 03-one-bundler.py

For each of compiler/typed/{rv32,frontend,async}/: checks that build.next.mjs builds exactly the committed bundles
(every generated byte identical), then moves build.next.mjs over build.mjs. Refuses if any bundle would differ.
"""
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[6]
TYPED = REPO / "compiler/typed"
DIRS = ("rv32", "frontend", "async")

check = """
import {readFileSync} from "node:fs";
const r = await import("./compiler/typed/rv32/build.next.mjs");
const f = await import("./compiler/typed/frontend/build.next.mjs");
const a = await import("./compiler/typed/async/build.next.mjs");
const out = {...r.bundles(), "typed-wasm.js": f.bundle(), "typed-async.js": a.bundle()};
console.log(JSON.stringify(Object.fromEntries(Object.entries(out).map(([file, text]) =>
    [file, readFileSync("compiler/typed/" + file, "utf8") === text]))));
"""
result = json.loads(subprocess.run(["node", "--input-type=module", "-e", check], cwd=REPO, check=True,
                                   capture_output=True, text=True).stdout)
print(result)
assert len(result) == 5 and all(result.values()), "a bundle would change"
for d in DIRS:
    nxt, old = TYPED / d / "build.next.mjs", TYPED / d / "build.mjs"
    assert nxt.exists() and old.exists(), d
    nxt.replace(old)
    print("moved", nxt.relative_to(REPO), "->", old.relative_to(REPO))
sys.exit(0)

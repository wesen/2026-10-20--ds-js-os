// Emit a fixed Chess layout program and independent canonical witnesses.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const dir=path.dirname(fileURLToPath(import.meta.url)), day=path.resolve(dir,'../../..');
const reference=path.join(day,fs.readdirSync(day).find(x=>x.startsWith('PICOCALC-RENDER-BINARY--')),'scripts/02-binary-screen.js');
const codec=vm.runInThisContext(fs.readFileSync(reference,'utf8')+';binaryScreen');
const states=fs.readFileSync(path.join(dir,'chess-trace.ndjson'),'utf8').trim().split('\n').map(JSON.parse);
const envelope = tree=>({app:'chess',title:'Chess',frame:{tree,hints:''}});
const digest=states[0].p;
assert(states.every(x=>x.p===digest && x.v===1));
// This layout comes from the declared semantic interface. Sentinel strings identify
// live slots in the layout only; no packet or field from the replay trains the plan.
const boardHole='$board', maskHole='$mask';
const example=envelope({v:1,p:digest,b:boardHole,m:maskHole,f:Array(9).fill(0)});
const sample=Buffer.from(codec.encode(example));
const n=sample.readUInt16LE(8), body=sample.readUInt16LE(13+2*n);
const dict=Array.from({length:n},(_,i)=>sample.toString('utf8',sample.readUInt16LE(13+2*i),sample.readUInt16LE(15+2*i)));
const constantStrings=dict.filter(x=>x!==boardHole && x!==maskHole);
const symbol=i=>dict[i]===boardHole?constantStrings.length:dict[i]===maskHole?constantStrings.length+1:constantStrings.indexOf(dict[i]);
const reloc=[], numerical=[], template=Buffer.from(sample.subarray(body));
function visit(slot,root=false) {
    const word=sample.readUIntLE(slot,3),tag=word>>>20,v=word&0xfffff;
    if(tag===5)reloc.push([slot-body,5,symbol(v)]);
    if(tag===6 || tag===7) {
        if(!root)reloc.push([slot-body,tag,v-body]);
        const children=sample.readUInt16LE(v);
        for(let i=0;i<children;i++) {
            const at=v+2+(tag===7?5:3)*i;
            if(tag===7) {
                reloc.push([at-body,0,symbol(sample.readUInt16LE(at))]);
                visit(at+2);
            } else {
                numerical.push(at-body);
                assert.equal(sample.readUIntLE(at,3),0x300000);
            }
        }
    }
}
visit(10,true);
assert.equal(numerical.length,9);
const list=a=>'{'+Array.from(a).join(',')+'}';
const cstr=s=>JSON.stringify(s);
let h='/* Generated by fixtures.mjs; canonical wire witnesses do not enter the encoder. */\n';
h+='static const char *const stage_vocab[] = {'+constantStrings.map(cstr).join(',')+'};\n';
h+='static const uint8_t stage_body[] = '+list(template)+';\n';
h+='static const uint8_t stage_slots[][3] = {'+reloc.map(list).join(',')+'};\n';
h+='static const uint8_t stage_numbers[] = '+list(numerical)+';\n';
h+='static const char stage_digest[] = '+cstr(digest)+';\n';
h+='static const struct { struct stage_input input; const char *json; unsigned length; uint8_t wire[576]; } stage_cases[] = {\n';
for(const state of states) {
    const units=[...state.b].map(x=>parseInt(x,16)).concat([...Buffer.from(state.m,'hex')],state.f.flatMap(x=>[x&65535,(x>>>16)&65535]));
    assert.equal(units.length,90);
    const payload=envelope(state), wire=codec.encode(payload);
    assert(wire.length<=576);
    h+='{{90,'+list(units)+'},'+cstr(JSON.stringify(payload))+','+wire.length+','+list(wire)+'},\n';
}
h+='};\n';
fs.writeFileSync(process.argv[2],h);
console.log(JSON.stringify({frames:states.length,constantStrings:constantStrings.length,structuralBytes:template.length,relocations:reloc.length,numericSlots:numerical.length}));

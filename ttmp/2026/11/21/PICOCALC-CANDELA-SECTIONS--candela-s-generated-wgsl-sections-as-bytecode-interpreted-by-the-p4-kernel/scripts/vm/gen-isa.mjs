// gen-isa.mjs: generate cdl_vm_isa.h (opcode numbers, operand specs, kernel-function signatures) from
// translator/isa.js, so the translator, the C verifier and the C interpreter share one definition.
// usage: node gen-isa.mjs <out.h>        (check mode: node gen-isa.mjs --check <existing.h>)
import { writeFileSync, readFileSync } from 'node:fs';
import * as ISA from '../translator/isa.js';

const lines = [];
const L = s => lines.push(s);
L('/* cdl_vm_isa.h: generated by vm/gen-isa.mjs from translator/isa.js (PICOCALC-CANDELA-SECTIONS). Do not edit. */');
L('#ifndef CDL_VM_ISA_H');
L('#define CDL_VM_ISA_H');
L(`#define CDL_VM_VERSION ${ISA.VERSION}`);
L(`#define CDL_VM_MAGIC 0x${ISA.MAGIC.toString(16)}u`);
L(`#define CDL_VM_MAX_REGS ${ISA.MAX_REGS}`);
L(`#define CDL_VM_MAX_CODE ${ISA.MAX_CODE}`);
L(`#define CDL_VM_HIT_IN 0x${ISA.HIT_IN.toString(16)}u`);
L(`#define CDL_VM_HIT_WORDS ${ISA.HIT_WORDS}`);
L(`#define CDL_VM_LOBE_WORDS ${ISA.LOBE_WORDS}`);
L(`#define CDL_VM_NENTRY ${ISA.ENTRIES.length}`);
L(`#define CDL_VM_NOPS ${ISA.OPS.length}`);
L(`#define CDL_VM_NKFUNC ${ISA.KFUNCS.length}`);
L('enum cdl_vm_op {');
for (const o of ISA.OPS) L(`  CDL_OP_${o.name} = ${o.code},`);
L('};');
L('enum cdl_vm_kfunc {');
ISA.KFUNCS.forEach((f, i) => L(`  CDL_K_${f.name} = ${i},`));
L('};');
L('enum cdl_vm_entry {');
ISA.ENTRIES.forEach((e, i) => L(`  CDL_E_${e.name} = ${i},`));
L('};');
L('/* Lobe fields in LOBE mask order: word offset and width */');
L('static const unsigned char cdl_vm_lobe_field[13][2] = {' + ISA.LOBE_ORDER.map(f => `{${ISA.LOBE_FIELDS[f][0]}, ${ISA.LOBE_FIELDS[f][1]}}`).join(', ') + '};');
L('/* Hit fields: word offset of each, in declaration order (ok and front are one-byte bools) */');
for (const [f, [off, w, t]] of Object.entries(ISA.HIT_FIELDS)) L(`#define CDL_HIT_${f} ${off}   /* ${w} word(s), ${t} */`);
for (const [f, [off, w, t]] of Object.entries(ISA.LOBE_FIELDS)) L(`#define CDL_LOBE_${f} ${off}   /* ${w} word(s), ${t} */`);
L('/* Operand specs per opcode (NULL: variable-length, decoded by the verifier\'s special cases); see isa.js. */');
L('static const char *const cdl_vm_sig[CDL_VM_NOPS] = {');
for (const o of ISA.OPS) L(`  /* ${o.name} */ ${o.sig ? JSON.stringify(o.sig.join(' ')) : 'NULL'},`);
L('};');
L('/* 1: the opcode H byte is a width (MOVN), 2: generic vector (width and broadcast flags) */');
L('static const unsigned char cdl_vm_hkind[CDL_VM_NOPS] = {' + ISA.OPS.map(o => (o.wide ? 1 : o.generic ? 2 : 0)).join(', ') + '};');
L('static const unsigned char cdl_vm_term[CDL_VM_NOPS] = {' + ISA.OPS.map(o => (o.term ? 1 : 0)).join(', ') + '};');
L('static const char *const cdl_vm_opname[CDL_VM_NOPS] = {' + ISA.OPS.map(o => JSON.stringify(o.name)).join(', ') + '};');
L('/* kernel functions: operand specs after the CALL halfword, and whether only customKernel may call them */');
L('static const char *const cdl_vm_ksig[CDL_VM_NKFUNC] = {' + ISA.KFUNCS.map(f => JSON.stringify(f.sig.join(' '))).join(', ') + '};');
L('static const unsigned char cdl_vm_kcustom[CDL_VM_NKFUNC] = {' + ISA.KFUNCS.map(f => (f.custom ? 1 : 0)).join(', ') + '};');
L('static const char *const cdl_vm_kname[CDL_VM_NKFUNC] = {' + ISA.KFUNCS.map(f => JSON.stringify(f.name)).join(', ') + '};');
L('/* entry argument and result widths */');
L('static const unsigned char cdl_vm_entry_args[CDL_VM_NENTRY] = {' + ISA.ENTRIES.map(e => e.args.reduce((s, [, t]) => s + { f32: 1, i32: 1, vec2f: 2, vec3f: 3 }[t], 0)).join(', ') + '};');
L('static const unsigned char cdl_vm_entry_ret[CDL_VM_NENTRY] = {' + ISA.ENTRIES.map(e => ({ Lobe: ISA.LOBE_WORDS, f32: 1, vec3f: 3 }[e.ret])).join(', ') + '};');
const LN = ISA.LOBE_NONE.map(x => (Array.isArray(x) ? `{.i = ${x[1]}}` : `{.f = ${Number.isInteger(x) ? x + '.0f' : x + 'f'}}`));
L('/* lobeNone() as words (kernel.js CORE) */');
L('#define CDL_VM_LOBE_NONE_INIT {' + LN.join(', ') + '}');
L('#endif');
const out = lines.join('\n') + '\n';
const args = process.argv.slice(2);
if (args[0] === '--check') { if (readFileSync(args[1], 'utf8') !== out) { console.error(args[1] + ' is stale: run gen-isa.mjs'); process.exit(1); } console.log(args[1] + ' is current'); }
else { writeFileSync(args[0], out); console.log(`${ISA.OPS.length} opcodes, ${ISA.KFUNCS.length} kernel functions -> ${args[0]}`); }

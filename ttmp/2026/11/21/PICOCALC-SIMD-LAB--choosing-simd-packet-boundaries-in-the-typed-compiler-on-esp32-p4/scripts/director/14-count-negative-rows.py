"""Count work a proved whole-sphere-row rejection could skip on the actual board fixtures."""
import argparse
import json
import re
import struct
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("header", type=Path, help="C header generated by scripts/ray/03-ceiling-fixtures.mjs")
args = parser.parse_args()
text = args.header.read_text()
result = {}
for scene in ["opening", "dense", "sparse"]:
    matched = re.search(rf"{scene}_raw\[4100\] = \{{([0-9,]+)\}};", text)
    buf = bytes(map(int, matched[1].split(",")))
    assert len(buf) == 4100 and struct.unpack_from("<I", buf)[0] == 2048
    cells = struct.unpack_from("<2048H", buf, 4)
    spheres = cells[16]
    negative = 0
    for sphere in range(spheres):
        cy, radius = cells[2+5*sphere], cells[4+5*sphere]
        negative += sum(radius*radius-(y-cy)*(y-cy) < 0 for y in range(160))
    result[scene] = {"sphereRows": spheres*160, "negativeSphereRows": negative,
                     "iterationsWithProvedNegativeRow": negative*160,
                     "allSourceIterations": spheres*160*160}
out = Path(__file__).resolve().parents[2]/"various/director/negative-rows.json"
out.write_text(json.dumps(result,indent=2)+"\n")
print(result)

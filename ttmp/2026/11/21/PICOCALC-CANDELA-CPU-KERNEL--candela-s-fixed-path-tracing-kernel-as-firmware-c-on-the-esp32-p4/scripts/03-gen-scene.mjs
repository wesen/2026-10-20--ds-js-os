// 03-gen-scene.mjs: one preset's generated sections as C++, and its packed buffers.
// usage: node 03-gen-scene.mjs <candela-root> <kernel-out-dir> <preset-id> <width> <height> <out-dir> [--check-only]
//
// Runs Candela's own front end (build, compile, pack) on the preset, splits compiled.shared with
// lib/candela.mjs, and translates the generated part (fields, materials, customKernel) against the kernel
// that 02-gen-kernel.mjs produced (its manifest gives the section API and the struct names). Writes
//   <ID>.inc   the sections: static functions, the five dispatch functions renamed sec_*
//   <ID>.cpp   a translation unit that compiles the sections against cdl_kernel.h and exports the
//              table NS_sections_<ID> (a stand-in for PICOCALC-CANDELA-SECTIONS' bytecode)
//   <ID>.bin   the packed buffers: 'CDL1', five u32 row counts, then U, O, LI, BV, SD rows (f32)
//   <ID>.json  sizes, camera exposure, engine settings
// With --check-only nothing is written: the preset must split, translate, and match the dispatch signatures.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { checkPin, loadKernel, loadCandela, loadPresets, splitProgram, exportScene } from './lib/candela.mjs';
import { translate, head, body } from './lib/wgsl2c.mjs';

const argv = process.argv.slice(2);
const checkOnly = argv.includes('--check-only');
const [root, kdir, id, W, H, outDir] = argv.filter(a => !a.startsWith('--'));
if (!outDir) { console.error('usage: node 03-gen-scene.mjs <candela-root> <kernel-out-dir> <preset-id> <width> <height> <out-dir> [--check-only]'); process.exit(2); }
checkPin(root);
const K = await loadKernel(root), C = await loadCandela(root);
const man = JSON.parse(readFileSync(join(kdir, 'manifest.json'), 'utf8'));
const preset = loadPresets(root).find(p => p.id === id);
if (!preset) throw new Error('no preset ' + id);
const DISPATCH = { evalMaterial: ['Lobe', ['Hit', 'vec3f', 'f32']], sdUser: ['f32', ['i32', 'vec3f']], heightAt: ['f32', ['i32', 'vec2f']],
  densityOf: ['f32', ['i32', 'vec3f']], customKernel: ['vec3f', ['vec3f', 'vec3f']] };

export function translateSections(shared, where) {
  const s = splitProgram(shared, K);
  const src = (s.fieldCode + s.matCode).replace(new RegExp(`\\b(${Object.keys(DISPATCH).join('|')})\\b`, 'g'), 'sec_$1');
  const t = translate(src, { where, known: [...man.sectionAPI, 'U', 'objF', 'litF', 'bvhF', 'sdF'], structs: man.kernel.structs,
    impure: { fns: man.kernel.sideEffects, globals: man.kernel.globals } });
  if (t.structs.length || t.globals.length || t.tables.length) throw new Error(`${where}: sections declare structs or module-scope state`);
  for (const [name, [ret, ps]] of Object.entries(DISPATCH)) {
    const f = t.fns.find(f => f.name === 'sec_' + name);
    if (!f) throw new Error(`${where}: no ${name}`);
    if (f.ret !== ret || f.params.map(p => p.type).join() !== ps.join()) throw new Error(`${where}: ${name} has signature (${f.params.map(p => p.type)}) -> ${f.ret}`);
  }
  return { split: s, t };
}

const { compiled, bin, meta } = await exportScene(root, C, preset, +W, +H);
const { split, t } = translateSections(compiled.shared, `${id} sections`);
const cid = id.replace(/\W/g, '_');
const inc = `// Generated by 03-gen-scene.mjs from Candela preset ${preset.base} (PICOCALC-CANDELA-CPU-KERNEL); do not edit.
// The scene's generated WGSL sections (fields, materials, customKernel), translated against cdl_kernel.h.
${t.consts.map(c => `static const ${c.type} ${c.name} = ${c.init};`).join('\n')}
${t.fns.map(f => head(f) + ';').join('\n')}
${t.fns.map(f => head(f) + body(f)).join('\n')}
`;
const cpp = `// Generated by 03-gen-scene.mjs (PICOCALC-CANDELA-CPU-KERNEL); do not edit.
// Preset ${id}'s sections compiled against the kernel instance CDL_NS; exports CDL_NS_sections_${cid}.
#include "cdl_kernel.h"
static_assert(CDL_SPECTRAL == ${split.spectral ? 1 : 0}, "preset ${id} needs a kernel instance with CDL_SPECTRAL=${split.spectral ? 1 : 0}");
namespace CDL_NS {
using namespace api;
#include "${id}.inc"
}
extern "C" const CDL_NS::Sections CDL_C(sections_${cid}) = {
  ${Object.keys(DISPATCH).map(n => `&CDL_NS::sec_${n}`).join(',\n  ')}
};
`;
const info = { ...meta, cid, spectral: split.spectral, customKernel: !split.customDefault, sectionFunctions: t.fns.length,
  sectionWGSLLines: (split.fieldCode + split.matCode).split('\n').length - 1, dataBytes: bin.length };
if (!checkOnly) {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, `${id}.inc`), inc);
  writeFileSync(join(outDir, `${id}.cpp`), cpp);
  writeFileSync(join(outDir, `${id}.bin`), bin);
  writeFileSync(join(outDir, `${id}.json`), JSON.stringify(info, null, 1) + '\n');
}
console.log(`${id}: ${t.fns.length} section functions from ${info.sectionWGSLLines} WGSL lines, ${bin.length} data bytes, ${meta.integrator} integrator, depth ${meta.maxDepth}${checkOnly ? ' (checked)' : ''}`);

// The runtime's statements, with its intrinsics: $arity, $drain, $hostArg, $hostCall, $hostEvent.
export function nativeWorldPrelude() {
  const fix = (x) => {
    if (x === null || typeof x !== 'object') return x;
    if (Array.isArray(x)) return x.map(fix);
    if (x.kind === 'Call' && x.fn.kind === 'Var') {
      const n = x.fn.name;
      if (n === '$arity') return Prim('fn_arity', x.args.map(fix));
      if (n === '$drain') return LibCall('Promise.$drain', []);
      if (n === '$hostArg') return Prim('host_arg', x.args.map(fix));
      if (n === '$hostCall') return Prim('host_call', x.args.map(fix));
      if (n === '$hostEvent') return Prim('host_event', x.args.map(fix));
      if (n === '$hostEntries') return Prim('host_entries', x.args.map(fix));
    }
    const out = {};
    for (const [k, v] of Object.entries(x)) out[k] = fix(v);
    return out;
  };
  return fix(parse(NATIVE_WORLD_SOURCE).body);
}

// A native world's program: the runtime, then the world's file, then the hand-over of the two
// entries: they are closures (over the program's variables), which the runtime keeps for the
// embedder. main runs the file; the kernel's events come through $nwInit and $nwEvent.
export function nativeWorldProgram(worldSrc) {
  const world = parse(worldSrc).body;
  const seen = new Set();
  const once = (d) => d.kind !== 'FunDef' || !d.name.includes('$') || !seen.has(d.name) && !!seen.add(d.name);
  const entries = parse('$hostEntries($nwInit, $nwEvent);').body.map((s) => ({ ...s, exp: Prim('host_entries', s.exp.args) }));
  return { kind: 'Program', body: [...nativeWorldPrelude(), ...world, ...entries].filter(once) };
}


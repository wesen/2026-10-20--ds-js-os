//
// Every world's compile above parses, infers and compiles the whole runtime again, though its code is
// the same in every world (its every value is Any). Compiled on its own instead, the runtime is a
// unit whose start ends by handing the values worlds use to $nat_export, in one record; a world is
// compiled on its own too, its uses of the runtime's names bound at its start to that record's slots
